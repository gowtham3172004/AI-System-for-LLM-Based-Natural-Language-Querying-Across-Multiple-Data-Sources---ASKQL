"""Dev tool: run the real AskQL UI with a stand-in LLM, so the UI can be explored/screenshotted without API keys.

    streamlit run scripts/ui_preview.py                 # models "work" (answers the demo-shop questions)
    PREVIEW_MODE=fail streamlit run scripts/ui_preview.py   # every model fails (shows the diagnostics UI)

Everything except the model is real: schema, SQL guard, DuckDB execution, grounding, charts, history.
NOT used in production - the app itself never contains a fake model.
"""
import json
import os
import re
import runpy
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.environ.update(HISTORY_DB_URL=f"sqlite:///{tempfile.gettempdir()}/askql_preview.db", GROQ_API_KEYS="", GEMINI_API_KEYS="",
                  OLLAMA_BASE_URL="", RATE_LIMIT_PER_MINUTE="1000", GLOBAL_RATE_LIMIT_PER_MINUTE="1000")

from langchain_core.messages import AIMessage  # noqa: E402
from langchain_core.runnables import RunnableLambda  # noqa: E402

import askql.service as service_mod  # noqa: E402
from askql.llm import LLMRouter  # noqa: E402
from askql.llm.factory import Candidate  # noqa: E402

FAIL = os.getenv("PREVIEW_MODE") == "fail"

SQL = [
    (r"monthly revenue|trend", "SELECT strftime(order_date, '%Y-%m') AS month, ROUND(SUM(total_amount), 2) AS revenue "
                               "FROM orders WHERE status = 'completed' GROUP BY 1 ORDER BY 1"),
    (r"top 5 customers", "SELECT c.name, ROUND(SUM(o.total_amount), 2) AS total_spend FROM orders o "
                         "JOIN customers c USING (customer_id) WHERE o.status = 'completed' GROUP BY c.name ORDER BY 2 DESC LIMIT 5"),
    (r"return rate", "SELECT p.category, ROUND(100.0 * SUM(CASE WHEN o.status = 'returned' THEN 1 ELSE 0 END) / COUNT(*), 1) "
                     "AS return_rate_pct FROM orders o JOIN products p USING (product_id) GROUP BY p.category ORDER BY 2 DESC"),
    (r"average order value|region", "SELECT c.region, ROUND(AVG(o.total_amount), 2) AS avg_order_value FROM orders o "
                                    "JOIN customers c USING (customer_id) GROUP BY c.region ORDER BY 2 DESC"),
    (r"how many|count|total number", "SELECT COUNT(*) AS total_orders, COUNT(DISTINCT customer_id) AS customers FROM orders"),
]


def fake(messages):
    system, user = messages[0].content, messages[-1].content
    if "expert data analyst who turns questions" in system:
        q = re.search(r"### Current question\n(.*?)(\n###|$)", user, re.S).group(1).strip().lower()
        if q in ("hi", "hello"):
            return AIMessage(content=json.dumps({"intent": "chat", "reply": "Hi! Ask me anything about your data."}))
        sql = next((s for p, s in SQL if re.search(p, q)), "SELECT * FROM orders ORDER BY order_date DESC LIMIT 10")
        return AIMessage(content=json.dumps({"intent": "sql", "sql": sql, "assumptions": None}))
    if "Columns:" not in user:  # e.g. the sidebar "Test connections" ping
        return AIMessage(content="OK")
    cols = [c.strip() for c in re.search(r"Columns: (.*)", user).group(1).split(",")]
    first = user.split("Preview (up to 20 rows):\n")[1].splitlines()[1].split(",")
    kind = "line" if cols[0] == "month" else "bar"
    one_row = len(user.split("Preview (up to 20 rows):\n")[1].strip().splitlines()) == 2
    return AIMessage(content=json.dumps({
        "answer": f"Here is the result for your question. The first row is **{first[0]}** with **{first[-1]}**.",
        "insights": ["Preview insight generated by the stand-in model (UI preview only)."],
        "chart": {"type": "none" if one_row else kind, "x": cols[0], "y": cols[-1], "title": " ".join(cols[-1].split("_")).title()},
        "followups": ["Break this down by region", "Show only completed orders"],
    }))


def dead(reason):
    def f(_):
        raise RuntimeError(reason)
    return RunnableLambda(f)


if FAIL:
    cands = [Candidate("groq", "groq:llama-3.3-70b-versatile (key 1)", lambda: dead("401 Invalid API Key")),
             Candidate("gemini", "gemini:gemini-2.0-flash (key 1)", lambda: dead("404 NOT_FOUND model no longer available"))]
else:
    cands = [Candidate("groq", "groq:llama-3.3-70b-versatile (key 1)", lambda: RunnableLambda(fake)),
             Candidate("gemini", "gemini:gemini-flash-latest (key 1)", lambda: RunnableLambda(fake))]
_router = LLMRouter(cands)
service_mod.build_router = lambda settings=None: _router

runpy.run_path(str(ROOT / "app" / "streamlit_app.py"), run_name="__main__")
